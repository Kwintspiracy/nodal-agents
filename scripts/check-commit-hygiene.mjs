#!/usr/bin/env node
// check-commit-hygiene.mjs — refuse a commit that carries damaged or stray files.
//
// Written after two failures on 2026-08-21, neither of which .gitignore could
// have caught, and neither of which a human reading `git status` did catch:
//
//   1. `packages/db/src/tests/helpers.ts` was committed with 16 NUL bytes at a
//      byte-identical length (34045 → 34045). A disk incident or an interrupted
//      write. Git had already classified the file as binary, so `git diff`
//      showed only an opaque `Bin 34045 -> 34045` and the damage was invisible.
//      It took down all 8 pglite suites in @nodal-agents/memory with a protocol
//      error that pointed nowhere near the real cause.
//
//   2. A validation report sitting at the repo root was swept in by `git add -A`
//      and failed the secret scan on a SHA-256 it contained.
//
// The lesson is not "read more carefully" — it is that both faults are
// mechanically detectable and neither is detectable by eye. So they are checked
// by machine, on the staged set, before the commit exists.
//
// Usage:
//   node scripts/check-commit-hygiene.mjs            # staged files (pre-commit)
//   node scripts/check-commit-hygiene.mjs --all      # every tracked file (CI)
//
// Exit 0 = clean. Exit 1 = something is wrong, with the fix spelled out.

import { execFileSync } from 'node:child_process';
import { readFileSync, statSync } from 'node:fs';

const ALL = process.argv.includes('--all');

/** Extensions whose content must be text. A NUL byte in one of these is damage. */
const TEXT_EXT =
  /\.(ts|tsx|js|jsx|mjs|cjs|json|md|mdx|css|scss|html|yml|yaml|sql|sh|txt|toml|env\.example)$/i;

/** Binary by nature — never inspected for NULs. */
const BINARY_EXT =
  /\.(png|jpe?g|gif|ico|webp|avif|svgz|woff2?|ttf|otf|eot|pdf|zip|tgz|gz|xlsx|docx|pptx|mp[34]|mov|wasm|node|bin|db|sqlite)$/i;

/**
 * Paths that have no business in a commit, matched against the repo-relative
 * path. Each entry says WHY, because a blocked commit with no explanation just
 * gets bypassed.
 */
const STRAY_RULES = [
  {
    re: /^[^/]+\.log$/i,
    why: 'a log file at the repo root — runtime output, not source',
  },
  {
    re: /^(validation|rapport|report)[-_].*\.md$/i,
    why: 'a validation report at the repo root; these belong in docs/validation/',
  },
  {
    re: /\.(tgz|zip)$/i,
    why: 'a build artefact; the pack is regenerated by `pnpm pack:build`',
  },
  {
    re: /^.*\.(orig|rej|bak)$/i,
    why: 'a merge or backup leftover',
  },
  {
    re: /(^|\/)(scratch|tmp|temp)[-_/]/i,
    why: 'scratch space; keep it out of the repository',
  },
  {
    re: /^.*\.(pem|key|p12|pfx)$/i,
    why: 'a private key or certificate — never commit these',
  },
];

/** Anything past this is almost certainly not source. */
const MAX_BYTES = 2 * 1024 * 1024;

function git(args) {
  return execFileSync('git', args, { encoding: 'utf-8', maxBuffer: 64 * 1024 * 1024 });
}

function stagedFiles() {
  // ACMR: added, copied, modified, renamed. Deletions have nothing to inspect.
  return git(['diff', '--cached', '--name-only', '--diff-filter=ACMR'])
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}

function trackedFiles() {
  return git(['ls-files'])
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}

const problems = [];

function report(file, what, fix) {
  problems.push({ file, what, fix });
}

const files = ALL ? trackedFiles() : stagedFiles();

for (const file of files) {
  let stat;
  try {
    stat = statSync(file);
  } catch {
    continue; // staged then removed from disk; git has the content either way
  }
  if (!stat.isFile()) continue;

  // ── Stray files ───────────────────────────────────────────────────────────
  for (const rule of STRAY_RULES) {
    if (rule.re.test(file)) {
      report(
        file,
        rule.why,
        `Unstage it (git restore --staged "${file}") and either move it somewhere ` +
          'it belongs or add it to .gitignore.',
      );
    }
  }

  if (BINARY_EXT.test(file)) continue;

  // ── Oversized ─────────────────────────────────────────────────────────────
  if (stat.size > MAX_BYTES) {
    report(
      file,
      `${(stat.size / 1024 / 1024).toFixed(1)} MB — too large for a source file`,
      'If it is a generated artefact, gitignore it. If it is genuinely needed, say so in review.',
    );
    continue;
  }

  if (!TEXT_EXT.test(file)) continue;

  // ── Damaged content ───────────────────────────────────────────────────────
  let buf;
  try {
    buf = readFileSync(file);
  } catch {
    continue;
  }

  let nulCount = 0;
  for (const byte of buf) if (byte === 0) nulCount++;

  if (nulCount > 0) {
    // The exact 2026-08-21 fault. A source file never legitimately contains a
    // NUL byte; when one appears, the file has been damaged, not edited.
    report(
      file,
      `${nulCount} NUL byte(s) in a text file — the content is damaged, not edited`,
      'Restore it from the last good commit: ' +
        `git checkout HEAD -- "${file}"  (or name an older commit). Then re-apply ` +
        'your changes and check the file still parses.',
    );
    continue;
  }

  // UTF-16 arrives when a Windows tool rewrites a file with the wrong encoding.
  // Everything downstream (tsc, eslint, prettier, git diff) then misreads it.
  if (
    buf.length >= 2 &&
    ((buf[0] === 0xff && buf[1] === 0xfe) || (buf[0] === 0xfe && buf[1] === 0xff))
  ) {
    report(
      file,
      'UTF-16 byte-order mark — this file should be UTF-8',
      'Re-save it as UTF-8. A PowerShell redirect (`>` or Set-Content without ' +
        '-Encoding utf8) is the usual culprit.',
    );
  }
}

// ── Verdict ─────────────────────────────────────────────────────────────────

if (problems.length === 0) {
  console.log(
    `Commit hygiene: clean (${files.length} ${ALL ? 'tracked' : 'staged'} file(s) inspected).`,
  );
  process.exit(0);
}

console.error(`\nCommit blocked — ${problems.length} problem(s):\n`);
for (const p of problems) {
  console.error(`  ${p.file}`);
  console.error(`    ${p.what}`);
  console.error(`    → ${p.fix}\n`);
}
console.error(
  'If one of these is genuinely intended, say so out loud in the commit message\n' +
    'and re-run with the check disabled: NODAL_SKIP_HYGIENE=1 git commit …\n',
);
process.exit(1);
