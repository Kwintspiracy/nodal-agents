// gen-protocol.ts — writes src/protocol.generated.ts from the single protocol
// module, packages/shared/src/device-protocol.ts (#950).
//
// The client has no runtime dependency, so it cannot import that module (it
// carries Zod). Its TYPES are printed here, fully expanded by the TypeScript
// checker, and its CONSTANTS (the protocol version, the capabilities, the route
// tables) are read from the module itself. Nothing is typed by hand: a test
// (src/tests/protocol-generated.test.ts) renders this again and compares, so a
// change to the protocol module that is not regenerated fails CI.
//
//   pnpm --filter @nodal-agents/device-client gen

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import * as protocol from '../../shared/src/device-protocol.ts';

const PROTOCOL_FILE = fileURLToPath(
  new URL('../../shared/src/device-protocol.ts', import.meta.url),
);
export const GENERATED_FILE = fileURLToPath(
  new URL('../src/protocol.generated.ts', import.meta.url),
);

/** The types of the protocol a device sees, in the order they are printed. */
export const PROTOCOL_TYPES = [
  'DeviceCapability',
  'DeviceCardChoice',
  'DeviceCardImage',
  'DeviceRunState',
  'DeviceDeliverable',
  'DeviceEvent',
  'DeviceEventType',
] as const;

/** The constants of the protocol a device uses. */
export const PROTOCOL_CONSTANTS = [
  'DEVICE_PROTOCOL_VERSION',
  'DEVICE_CAPABILITIES',
  'DEVICE_GESTURES',
  'DEVICE_PAIRING_GESTURES',
  'DEVICE_POLL_STATUS',
] as const;

function printTypes(): string[] {
  const program = ts.createProgram([PROTOCOL_FILE], {
    strict: true,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    allowImportingTsExtensions: true,
    noEmit: true,
    skipLibCheck: true,
  });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(PROTOCOL_FILE);
  if (!source) throw new Error(`gen-protocol: cannot read ${PROTOCOL_FILE}`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  if (!moduleSymbol) throw new Error('gen-protocol: the protocol module has no exports');
  const exports = new Map(checker.getExportsOfModule(moduleSymbol).map((s) => [s.name, s]));
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  const flags =
    ts.NodeBuilderFlags.NoTruncation |
    ts.NodeBuilderFlags.InTypeAlias |
    ts.NodeBuilderFlags.MultilineObjectLiterals |
    ts.NodeBuilderFlags.IgnoreErrors;

  return PROTOCOL_TYPES.map((name) => {
    const symbol = exports.get(name);
    if (!symbol) throw new Error(`gen-protocol: the protocol module exports no type ${name}`);
    const type = checker.getDeclaredTypeOfSymbol(symbol);
    const node = checker.typeToTypeNode(type, undefined, flags);
    if (!node) throw new Error(`gen-protocol: cannot print type ${name}`);
    const printed = printer.printNode(ts.EmitHint.Unspecified, node, source);
    return `export type ${name} = ${printed};`;
  });
}

function printConstants(): string[] {
  const values = protocol as unknown as Record<string, unknown>;
  return PROTOCOL_CONSTANTS.map((name) => {
    if (!(name in values)) throw new Error(`gen-protocol: the protocol module exports no ${name}`);
    const json = JSON.stringify(values[name], null, 2);
    return `export const ${name} = ${json} as const;`;
  });
}

/** The whole generated file, as it must be on disk. */
export function renderProtocol(): string {
  return [
    '// protocol.generated.ts — GENERATED by scripts/gen-protocol.ts from',
    '// packages/shared/src/device-protocol.ts. Do not edit: run',
    '// `pnpm --filter @nodal-agents/device-client gen`.',
    '',
    ...printConstants().flatMap((s) => [s, '']),
    ...printTypes().flatMap((s) => [s, '']),
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(GENERATED_FILE, renderProtocol());
  console.warn(`wrote ${GENERATED_FILE}`);
}
